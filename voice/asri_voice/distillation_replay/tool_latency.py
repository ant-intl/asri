"""Deterministic virtual tool latency for distillation replay.

Replay tool results are generated by a mock service, so mock wall-clock latency
must not decide whether a tool is visible in a HeartBeat snapshot.  This module
keeps the virtual tool timeline stable and reproducible.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass
from typing import Any


@dataclass(frozen=True)
class ToolLatencyTier:
    name: str
    weight: int
    min_ms: int
    max_ms: int


TOOL_LATENCY_TIERS: tuple[ToolLatencyTier, ...] = (
    ToolLatencyTier("instant", 50, 1, 10),
    ToolLatencyTier("fast", 30, 20, 100),
    ToolLatencyTier("normal", 15, 200, 800),
    ToolLatencyTier("slow", 5, 1000, 3000),
)


def _stable_u32(key: str) -> int:
    return int(hashlib.sha1(key.encode("utf-8")).hexdigest()[:8], 16)


def stable_tool_latency_tier(tool_name: str) -> ToolLatencyTier:
    """Assign a stable latency tier from the tool name.

    The intended replay mix is:
    instant 50%, fast 30%, normal 15%, slow 5%.
    """
    bucket = _stable_u32(f"tier:{tool_name}") % 100
    cumulative = 0
    for tier in TOOL_LATENCY_TIERS:
        cumulative += tier.weight
        if bucket < cumulative:
            return tier
    return TOOL_LATENCY_TIERS[-1]


def stable_virtual_tool_latency_ms(
    *,
    tool_name: str,
    arguments: dict[str, Any] | dict,
    salt: str = "",
) -> int:
    """Return deterministic virtual latency for a tool call.

    The tool name fixes the broad latency tier.  Arguments and salt only pick a
    deterministic value inside that tier, so the same backend tool has a stable
    latency class while individual calls avoid looking mechanically identical.
    """
    tier = stable_tool_latency_tier(tool_name)
    if tier.max_ms <= tier.min_ms:
        return tier.min_ms
    normalized_arguments = json.dumps(
        arguments or {},
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
    )
    key = f"latency:{tier.name}:{tool_name}:{normalized_arguments}:{salt}"
    return tier.min_ms + (_stable_u32(key) % (tier.max_ms - tier.min_ms + 1))
